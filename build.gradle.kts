import com.diffplug.spotless.kotlin.KtfmtStep.KtfmtFormattingOptions
import com.diffplug.spotless.kotlin.KtfmtStep.TrailingCommaManagementStrategy

plugins {
    alias(libs.plugins.android.application) apply false
    alias(libs.plugins.hilt.android) apply false
    alias(libs.plugins.kotlin.compose) apply false
    alias(libs.plugins.ksp) apply false
    alias(libs.plugins.licensee) apply false
    alias(libs.plugins.spotless)
}

spotless {
    val ktfmtVersion = checkNotNull(libs.ktfmt.get().version)
    val licenseHeader = rootProject.file("spotless/license-header.txt")

    // Keep in sync with the ktfmt IDE plugin settings in .idea/ktfmt.xml
    val ktfmtOptions: (KtfmtFormattingOptions) -> Unit = {
        it.setMaxWidth(120)
        it.setBlockIndent(4)
        it.setContinuationIndent(4)
        it.setTrailingCommaManagementStrategy(TrailingCommaManagementStrategy.COMPLETE)
    }

    kotlin {
        target("app/src/**/*.kt")
        targetExclude("**/build/**")
        ktfmt(ktfmtVersion).kotlinlangStyle().configure(ktfmtOptions)
        licenseHeaderFile(licenseHeader)
    }

    kotlinGradle {
        target("**/*.gradle.kts")
        targetExclude("**/build/**")
        ktfmt(ktfmtVersion).kotlinlangStyle().configure(ktfmtOptions)
        licenseHeaderFile(licenseHeader, "(plugins|pluginManagement|buildscript|import)")
    }

    format("misc") {
        target(
            "**/.gitignore",
            ".editorconfig",
            "**/*.properties",
            "gradle/*.toml",
            "app/proguard-rules.pro",
            "app/src/**/*.xml",
            "Gemfile",
            "fastlane/Appfile",
            "fastlane/Fastfile",
            "fastlane/Screengrabfile",
            "fastlane/*.py",
            ".githooks/*",
        )
        // License texts are shown verbatim in the app; store metadata is uploaded as-is
        targetExclude("**/build/**", "app/src/main/res/raw/**", "fastlane/metadata/**", ".idea/**", ".gradle/**")
        trimTrailingWhitespace()
        leadingTabsToSpaces()
        endWithNewline()
    }

    flexmark {
        target("**/*.md")
        // fastlane/README.md is generated by fastlane
        targetExclude("**/build/**", "fastlane/README.md", ".idea/**", ".gradle/**")
        flexmark()
    }
}

buildscript {
    dependencies {
        classpath(libs.oss.licenses.plugin)
    }
}
